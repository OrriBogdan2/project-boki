def gen_controls():
    src = open(os.path.join(ROOT, "scripts", "core", "game.gd"), encoding="utf-8").read()
    acts = gd_const("core/settings.gd", "ACTIONS") or []
    label = {a[0]: a[1] for a in acts}
    keys = {}
    for m in re.finditer(r'_key\("([a-z_0-9]+)",\s*\[([^\]]*)\](?:,\s*(MOUSE_BUTTON_[A-Z0-9]+))?\)\s*(?:#\s*(.*))?', src):
        a, ks, mb, note = m.group(1), m.group(2), m.group(3), (m.group(4) or "").strip()
        names = []
        for k in re.findall(r'KEY_([A-Z0-9]+)', ks):
            names.append({"QUOTELEFT": "`", "ESCAPE": "Esc", "CTRL": "Ctrl", "SHIFT": "Shift", "SPACE": "Space", "TAB": "Tab"}.get(k, k.title() if k.isalpha() and len(k) > 1 else k))
        if mb:
            names.append({"MOUSE_BUTTON_LEFT": "Left click", "MOUSE_BUTTON_RIGHT": "Right click", "MOUSE_BUTTON_MIDDLE": "Middle mouse", "MOUSE_BUTTON_XBUTTON1": "Mouse 4", "MOUSE_BUTTON_XBUTTON2": "Mouse 5"}.get(mb, mb))
        e = keys.setdefault(a, {"keys": [], "note": ""})
        e["keys"] += [n for n in names if n not in e["keys"]]
        if note and not e["note"]: e["note"] = note
    rows = []
    for a, e in keys.items():
        if not e["keys"]:
            continue      # placeholders kept for old code paths (no default key)
        rows.append([" / ".join(e["keys"]), label.get(a, a.replace("_", " ").capitalize()), "`%s`" % a, ("yes" if a in label else "no")])
    body = "Default bindings, read from `Game._setup_input` (`scripts/core/game.gd`); names from the controls list in `Settings.ACTIONS`. "
    body += "\"Rebindable\" means it's listed in Settings > Controls.\n\n" + table(["Key", "Action", "Id", "Rebindable"], rows)
    block("Controls.md", "keys", body)

