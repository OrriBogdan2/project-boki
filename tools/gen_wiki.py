#!/usr/bin/env python3
"""Generates the data-driven pages of the Project Boki wiki (docs/wiki/) from the game's own data,
so the wiki stays in step with the game.

    python3 tools/gen_wiki.py            # write the pages, print what changed
    python3 tools/gen_wiki.py --check    # write nothing; exit 1 if any page is out of date

Plain Python 3, no Godot needed. Idempotent: running it twice changes nothing the second time.

Sources: content/ (archetypes, dash_flow, classes, kin_v2, kin, abilities_v2, merges_v2, evolution_v2,
mutations, gloves, weapons, abilities, maps, biomes, combos, rules) and a few constant tables read
straight out of the GDScript (Data.CLASSES, Data.TIERS, Life.R, Care.BONDS, HomeLayout.CATALOG...).
Those are parsed as literals; if one stops parsing, the script says which and carries on.

Two kinds of output:
  * whole pages, written from scratch (they start with a "generated" note: don't edit them);
  * blocks inside hand-written pages, between <!-- gen:NAME --> and <!-- /gen:NAME --> markers.
    Only the text between the markers is replaced; everything else on the page is left alone.
"""
import ast, glob, json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
WIKI = os.path.join(ROOT, "docs", "wiki")
NOTE = "<!-- Generated by tools/gen_wiki.py from the game's data. Don't edit by hand: change the data and rerun it. -->"
WARN = []

# ------------------------------------------------------------------ reading data
def rel(p):
    return os.path.relpath(p, ROOT).replace(os.sep, "/")

def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)

def content(kind):
    """{id: dict} for every JSON file in content/<kind>, sorted by file name."""
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "content", kind, "*.json"))):
        try:
            out[os.path.splitext(os.path.basename(p))[0]] = load_json(p)
        except Exception as e:  # a broken file shouldn't stop the rest
            WARN.append("%s: %s" % (rel(p), e))
    return out

def _strip_gd(src):
    """GDScript literal text -> Python literal text: comments dropped, Color/Vector calls and
    true/false/null turned into Python values. Strings are left exactly as they are."""
    out, i, n = [], 0, len(src)
    code = []
    def flush():
        s = "".join(code)
        s = re.sub(r'Color\(\s*"([0-9a-fA-F]+)"\s*\)', r'"#\1"', s)
        s = re.sub(r'\b(?:Color|Vector[234]i?)\(([^()]*)\)', r'[\1]', s)
        s = re.sub(r'\btrue\b', 'True', s)
        s = re.sub(r'\bfalse\b', 'False', s)
        s = re.sub(r'\bnull\b', 'None', s)
        s = re.sub(r'\bINF\b', '1e999', s)
        out.append(s)
        code.clear()
    while i < n:
        c = src[i]
        if c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            flush()
            # Color("x") spans a string: handle it before the string leaves the code buffer
            out.append(src[i:j + 1])
            i = j + 1
        elif c == "#":
            while i < n and src[i] != "\n":
                i += 1
        else:
            code.append(c)
            i += 1
    flush()
    txt = "".join(out)
    # Color("x") was split by the string handling above: join it back
    txt = re.sub(r'\b(?:Color)\(\s*("[^"]*")\s*\)', lambda m: '"#' + m.group(1)[1:], txt)
    return txt

def gd_const(script, name):
    """The value of `const NAME := <literal>` in scripts/<script>, as Python data (None if it
    can't be read)."""
    path = os.path.join(ROOT, "scripts", script)
    try:
        src = open(path, encoding="utf-8").read()
    except OSError:
        WARN.append("missing %s (for %s)" % (script, name))
        return None
    m = re.search(r'^const %s\s*(?::[^=]*)?:?=\s*' % re.escape(name), src, re.M)
    if not m:
        WARN.append("%s: no const %s" % (script, name))
        return None
    i = m.end()
    if src[i] not in "[{":
        line = src[i:src.index("\n", i)]
        txt = _strip_gd(line).strip()
    else:
        depth, j, instr = 0, i, False
        while j < len(src):
            c = src[j]
            if instr:
                if c == "\\": j += 1
                elif c == '"': instr = False
            elif c == '"': instr = True
            elif c == "#":
                j = src.index("\n", j); continue
            elif c in "[{(": depth += 1
            elif c in "]})":
                depth -= 1
                if depth == 0: break
            j += 1
        txt = _strip_gd(src[i:j + 1])
    try:
        return ast.literal_eval(txt)
    except Exception as e:
        WARN.append("%s: couldn't read const %s (%s)" % (script, name, e.__class__.__name__))
        return None

def gd_dict_comments(script, name):
    """{key: trailing comment} for a one-key-per-line const dictionary."""
    src = open(os.path.join(ROOT, "scripts", script), encoding="utf-8").read()
    m = re.search(r'^const %s\s*:?=\s*\{(.*?)^\}' % re.escape(name), src, re.M | re.S)
    out = {}
    if m:
        for line in m.group(1).splitlines():
            k = re.match(r'\s*"([a-z_0-9]+)"\s*:.*?#\s*(.*)$', line)
            if k:
                out[k.group(1)] = re.sub(r'\s*\[[^\]]*\]\s*', ' ', k.group(2)).strip()
    return out

# ------------------------------------------------------------------ helpers
def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")

def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        out.append("| " + " | ".join(esc(x) for x in r) + " |")
    return "\n".join(out)

def num(x):
    if isinstance(x, float):
        return ("%g" % x)
    return str(x)

def secs(x):
    return "%ss" % num(x) if x not in (None, "") else ""

def link(page, text=None):
    return "[%s](%s.md)" % (text or page.replace("-", " "), page)

def slug(s):
    return re.sub(r"[^a-z0-9 -]", "", s.lower()).replace(" ", "-")

WRITTEN, SAME = [], []
CHECK = "--check" in sys.argv

def write(name, text, folder=WIKI):
    path = os.path.join(folder, name)
    text = text.rstrip() + "\n"
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old == text:
        SAME.append(name); return
    WRITTEN.append(rel(path))
    if not CHECK:
        os.makedirs(folder, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

def page(name, title, body, sources):
    src = ", ".join("`%s`" % s for s in sources)
    write(name, "%s\n# %s\n\n_Generated from %s._\n\n%s" % (NOTE, title, src, body.strip()))

def block(name, key, body):
    """Replace the text between <!-- gen:key --> and <!-- /gen:key --> in a hand-written page."""
    path = os.path.join(WIKI, name)
    if not os.path.exists(path):
        WARN.append("%s: page missing, block '%s' not written" % (name, key)); return
    old = open(path, encoding="utf-8").read()
    a, b = "<!-- gen:%s -->" % key, "<!-- /gen:%s -->" % key
    if a not in old or b not in old:
        WARN.append("%s: no markers for block '%s'" % (name, key)); return
    pre, rest = old.split(a, 1)
    _, post = rest.split(b, 1)
    new = pre + a + "\n" + NOTE + "\n\n" + body.strip() + "\n\n" + b + post
    if new == old:
        SAME.append("%s#%s" % (name, key)); return
    WRITTEN.append("%s#%s" % (rel(path), key))
    if not CHECK:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)

