# ------------------------------------------------------------------ Boki
def ability_line(aid):
    a = AB2.get(aid)
    if not a: return "`%s` (missing)" % aid
    bits = []
    if a.get("cooldown"): bits.append("%s cooldown" % secs(a["cooldown"]))
    if a.get("charges", 1) != 1: bits.append("%s charges" % num(a["charges"]))
    if a.get("range"): bits.append("range %sm" % num(a["range"]))
    return "**%s** (%s). %s" % (a["name"], ", ".join(bits), a.get("flavor", ""))

