        a, ks, mb, note = m.group(1), m.group(2), m.group(3), (m.group(4) or "").strip()
        names = []
        for k in re.findall(r'KEY_([A-Z0-9]+)', ks):
            names.append({"QUOTELEFT": "`", "ESCAPE": "Esc", "CTRL": "Ctrl", "SHIFT": "Shift", "SPACE": "Space", "TAB": "Tab"}.get(k, k.title() if k.isalpha() and len(k) > 1 else k))
