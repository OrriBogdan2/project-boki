"""make_rig13.py: regenerates rig13.py = build_head.py + the rig stage of ../hem_r11/rig11.py (mode A weights, slit, per-frame SkirtSw solve)."""

import os

d = os.path.dirname(os.path.abspath(__file__))
src = open(d + "/../hem_r11/rig11.py").read().split("\n")
i0 = [k for k, ln in enumerate(src) if ln.startswith("O = dict(")][0] + 1
i1 = [k for k, ln in enumerate(src) if ln.startswith("bpy.ops.wm.read_factory_settings")][0]
cfg = "\n".join(src[i0:i1])
i = [k for k, ln in enumerate(src) if ln.startswith("AMW = arm.matrix_world")][0]
body = "\n".join(src[i:])
slit = 'SLIT = (-165, -45, 0.90) if MODE == "A" else None'
assert slit in body
body = body.replace(
    slit, "SLIT = tuple(float(x) for x in O.get('slit', '-150,-60,0.90').split(',')) if MODE == 'A' else None"
)
ps = "hh_ = PIV - p.z\n"
assert ps in body
body = body.replace(ps, ps + "            if p.z < F('zlow', 0.0) or p.z > F('zhigh', 9.0): continue\n")
gv = "G = sk.vertex_groups\n"
assert gv in body
body = body.replace(
    gv,
    "ps = ps * (1 - (1 - F('pslow', 1.0)) * ss(F('pl0', .45), F('pl1', .95), np.clip((ZT - P[:, 2]) / (ZT - ZH), 0, 1)))\n"
    + gv,
    1,
)
assert "export_skins=True," in body
body = body.replace("export_skins=True,", "export_skins=True, export_all_influences=True,")
head = open(d + "/build_head.py").read()
doc = '"""rig13.py (generated by make_rig13.py): build_head.py + rig11 mode A weights/keys.\nblender -b -P rig13.py -- LIVE.glb OUT.glb [sk= sktex= ww= wd= kw= zhem= tris= | them= sh=0 slit=a,b,z keep=Idle,Attack marg=]"""\n'
open(d + "/rig13.py", "w").write(doc + head + "\n" + cfg + "\n" + body)
